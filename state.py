from typing import Any


def create_state(query: str) -> dict[str, Any]:
    """
    Shared workflow state.
    Every agent reads and updates this dictionary.
    """

    return {

        # ==================================================
        # User Input
        # ==================================================

        "query": query,

        # ==================================================
        # Metadata
        # ==================================================

        "date": "",

        "research_id": "",

        # ==================================================
        # Planner
        # ==================================================

        "sub_questions": "",

        # ==================================================
        # Research
        # ==================================================

        "research": [],

        "citations": [],

        # ==================================================
        # Statistics
        # ==================================================

        "statistics": {

            "questions": 0,

            "sources": 0,

            "unique_domains": 0,

            "execution_time": 0,

        },

        # ==================================================
        # Writer
        # ==================================================

        "draft": "",

        # ==================================================
        # Critic
        # ==================================================

        "review": "",

        "approved": False,

        # ==================================================
        # Logs
        # ==================================================

        "logs": [],
    }